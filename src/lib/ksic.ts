export type CompanyIndustry = keyof typeof KSIC_GROUPS;
export const COMPANY_INDUSTRIES = Object.keys(KSIC_GROUPS) as CompanyIndustry[];

export function ksicOptions(industry: string): string[] {
  const group = (KSIC_GROUPS as Record<string, Group>)[industry];
  if (!group) return [];
  return [
    ...group.core.map(([code, name]) => `[핵심] ${code} ${name}`),
    ...group.related.map(([code, name]) => `[연관] ${code} ${name}`),
  ];
}
